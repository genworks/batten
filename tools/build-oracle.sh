# build-oracle.sh SMLIB_SRC OUT_DIR
#
# Build NLib alone, from NVIDIA's usd-brep source (SMLIB_SRC is its
# source/SMLib directory), as the oracle Batten's tests compare against:
# OUT_DIR/libnlib-oracle.so, and OUT_DIR/oracle-symbols.sexp mapping each
# routine compiled with C++ linkage to its mangled symbol.
#
# Every NL_*.cpp is compiled with NLIB_UNUSED defined: NVIDIA fences routines
# it does not call in #if NLIB_UNUSED, and some of them are ones Batten
# ports.  A few of those fenced routines have bit-rotted; they are patched
# here, in a copy of the source, never in place:
#   NL_CrvFit.cpp   uses NLib's old unprefixed names (MTOL, INP_ERR ...):
#                   compiled with a header mapping them to NL_ names.
#   NL_SrfTool.cpp  uses eps, whose definition the source has commented out
#                   (// NL_PRIVATE NL_REAL eps = 1.0e-03;): restored.
#   NL_SrfAdv.cpp   N_SrfNonRatBasisDerivs is passed an old NL_REAL **** BD
#                   in one fenced caller Batten does not port: cast so it
#                   compiles.
#   NL_SrfShape.cpp the same stale BD in one fenced caller: cast the same way.
#   NL_VolumeAdv.cpp: its fenced routines are not ported
#                   and do not compile; built without NLIB_UNUSED.
set -euo pipefail
SMLIB_SRC=$(cd "${1:?usage: build-oracle.sh SMLIB_SRC OUT_DIR}" && pwd)
OUT=${2:?usage: build-oracle.sh SMLIB_SRC OUT_DIR}
mkdir -p "$OUT/src" "$OUT/obj"
OUT=$(cd "$OUT" && pwd)

# NLib cannot be linked alone: its headers pull in the kernel's smos_ utilities
# and inline members of Sm classes.  The oracle is the whole kernel, with only
# the NL_ files compiled as described above.
# -p keeps the sources' times, so unchanged objects are not rebuilt
cp -p "$SMLIB_SRC"/src/*.cpp "$OUT/src/"

sed -i 's|^// NL_PRIVATE NL_REAL eps = 1.0e-03;|NL_PRIVATE NL_REAL eps = 1.0e-03;|' "$OUT/src/NL_SrfTool.cpp"
sed -i 's|vdr, BD, &usp, &vsp );|vdr, *(NL_BASISDERIVATIVES *) BD, \&usp, \&vsp );|' "$OUT/src/NL_SrfAdv.cpp"
# line 2504 only: the identical call at line 1440 already passes the struct
sed -i '2504s|udh\[k\], vdh\[k\], BD, &spu, &spv );|udh[k], vdh[k], *(NL_BASISDERIVATIVES *) BD, \&spu, \&spv );|' "$OUT/src/NL_SrfShape.cpp"

cat > "$OUT/src/oracle-short-names.h" <<'EOF'
/* NLib's pre-10 unprefixed names, for fenced routines that still use them. */
#define MTOL     NL_MTOL
#define PTOL     NL_PTOL
#define LTOL     NL_LTOL
#define INP_ERR  NL_INP_ERR
#define CAL_ERR  NL_CAL_ERR
#define NUM_ERR  NL_NUM_ERR
#define MEM_ERR  NL_MEM_ERR
#define PAR_ERR  NL_PAR_ERR
#define YES      NL_YES
#define NO       NL_NO
EOF

FLAGS="-std=c++17 -O2 -fPIC -w -DNDEBUG -DNOMINMAX -I$SMLIB_SRC/inc"
# at most JOBS compiles at once: one per file at once (180) squeezes the
# other containers on a shared host into swap
JOBS=${JOBS:-8}
pids=()
for f in "$OUT"/src/*.cpp; do
  b=$(basename "$f" .cpp)
  case "$b" in
    shims) continue ;;
    NL_VolumeAdv) extra="" ;;
    NL_CrvFit) extra="-DNLIB_UNUSED=1 -include $OUT/src/oracle-short-names.h" ;;
    NL_*) extra="-DNLIB_UNUSED=1" ;;
    *) extra="" ;;
  esac
  # objects already built from an unchanged copy are kept
  if [ ! -f "$OUT/obj/$b.o" ] || [ "$f" -nt "$OUT/obj/$b.o" ] || [ "$0" -nt "$OUT/obj/$b.o" ]; then
    while [ "$(jobs -rp | wc -l)" -ge "$JOBS" ]; do wait -n || fail=1; done
    g++ $FLAGS $extra -c "$f" -o "$OUT/obj/$b.o" 2> "$OUT/obj/$b.err" &
  fi
done
fail=${fail:-0}
while [ "$(jobs -rp | wc -l)" -gt 0 ]; do wait -n || fail=1; done
if [ $fail -ne 0 ]; then
  for e in "$OUT"/obj/*.err; do [ -s "$e" ] && { echo "== $e"; grep -m5 error "$e"; }; done
  exit 1
fi

g++ -shared -static-libstdc++ -static-libgcc -Wl,--no-undefined -o "$OUT/libnlib-oracle.so" \
  $(ls "$OUT"/obj/*.o | grep -v '/shims.o$')

# Routines that lost C linkage (fenced ones have no prototype in an extern "C"
# block): name -> mangled symbol, for the CFFI bindings.
{
  echo ";;; Generated by build-oracle.sh: NLib routines with C++ linkage."
  echo "("
  nm -D --defined-only "$OUT/libnlib-oracle.so" | awk '$2 == "T" && $3 ~ /^_Z/ {print $3}' |
    while read -r sym; do
      name=$(echo "$sym" | c++filt | sed -E 's/\(.*//')
      case "$name" in N_*|S_*|U_*|G_*|A_*) printf ' ("%s" . "%s")\n' "$name" "$sym" ;; esac
    done
  echo ")"
} > "$OUT/oracle-symbols.sexp"

echo "built $OUT/libnlib-oracle.so: $(nm -D --defined-only "$OUT/libnlib-oracle.so" | awk '$2=="T"' | wc -l) routines, $(grep -c '^ ("' "$OUT/oracle-symbols.sexp") with C++ linkage"

# The shims and their CFFI bindings, for every routine in the manifest.
HERE=$(cd "$(dirname "$0")" && pwd)
python3 -I "$HERE/gen_oracle.py" "$SMLIB_SRC/src" "$HERE/manifest.sexp" "$OUT/libnlib-oracle.so" \
  "$OUT/oracle-symbols.sexp" "$OUT/src/shims.cpp" "$HERE/../tests/oracle-bindings.lisp"
g++ $FLAGS -c "$OUT/src/shims.cpp" -o "$OUT/obj/shims.o"
g++ -shared -static-libstdc++ -static-libgcc -o "$OUT/libnlib-oracle-shims.so" "$OUT/obj/shims.o" \
  -L"$OUT" -lnlib-oracle -Wl,-rpath,'$ORIGIN'
echo "built $OUT/libnlib-oracle-shims.so"
