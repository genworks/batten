"""gen_constants.py SMLIB_INC OUT_LISP

Every numeric #define NL_NAME in NLib's headers as a Lisp constant +name+
(NL_LEFT -> +left+, NL_PAR_ERR -> +par-err+), so ported routines pass NLib's
flags as the C does.  Constants defined by expressions (NL_NOZ, NL_BIGD ...)
are hand-written in src/types.lisp.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from nlib_names import hyphenate  # noqa: E402

inc, out = sys.argv[1:3]
seen = {}
for fn in sorted(os.listdir(inc)):
    if not (fn.startswith("NL_") or fn == "nurbs.h") or not fn.endswith(".h"):
        continue
    for line in open(os.path.join(inc, fn), encoding="latin-1"):
        m = re.match(r'\s*#\s*define\s+NL_(\w+)\s+\(?\s*(-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)\s*\)?\s*(?:/[*/].*)?$', line)
        if m and m.group(1) not in seen:
            seen[m.group(1)] = (m.group(2), fn)

HAND = {"BIGD", "SMAD", "NOZ", "NOW", "INFINITE", "UNDEFINED"}
with open(out, "w") as o:
    o.write(";;;; SPDX-FileCopyrightText: Copyright (c) 2020-2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n")
    o.write(";;;; SPDX-FileCopyrightText: Copyright (c) 2026 Genworks International\n")
    o.write(";;;; SPDX-License-Identifier: Apache-2.0\n;;;;\n")
    o.write(";;;; NLib's numeric constants (usd-brep source/SMLib/inc/NL_*.h): each\n")
    o.write(";;;; #define NL_NAME as +name+.  Generated by tools/gen_constants.py.\n\n")
    o.write("(in-package :batten)\n\n")
    for name, (val, fn) in seen.items():
        if name in HAND:
            continue
        lisp = "+" + hyphenate(name) + "+"
        if re.search(r'[.eE]', val):
            v = repr(float(val)).replace("e", "d")
            v = v if "d" in v else v + "d0"
        else:
            v = val
        o.write(f"(defconstant {lisp} {v}) ; NL_{name}, {fn}\n")
print(f"{len(seen)} constants")
